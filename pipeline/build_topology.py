"""
Step 2 · Build the map file and tract attributes from the Census boundaries.

    python pipeline/build_topology.py [--simplify 0.0004]

Reads  pipeline/raw/cb_2020_48_tract_500k.zip and cb_2020_48_place_500k.zip
Writes data/tracts_topo.js        window.HL_TOPO = TopoJSON {tracts (GEOID, CO), counties (CO)}
       pipeline/work/tract_geo.csv  GEOID, tract name, county FIPS, place names, land area (sq mi)

Counties are dissolved from the tracts so the two layers share borders exactly. Water-only tracts
(no land area) are dropped. A tract gets the names of the places that cover at least 20% of it.
"""
import argparse
import json

import geopandas as gpd
import topojson as tp

import config as C

SQM_PER_SQMI = 2_589_988.11
PLACE_SHARE = 0.20


def read(path_or_zip):
    p = str(path_or_zip)
    return gpd.read_file(("zip://" + p) if p.endswith(".zip") else p)


def place_names(tr, pl):
    """GEOID -> 'Place A, Place B' for places covering >= PLACE_SHARE of the tract (equal-area CRS)."""
    a = tr[["GEOID", "geometry"]].to_crs(5070)
    b = pl[["NAME", "geometry"]].to_crs(5070)
    area = a.set_index("GEOID").area
    ov = gpd.overlay(a, b, how="intersection", keep_geom_type=True)
    ov["share"] = ov.area / ov["GEOID"].map(area)
    ov = ov[ov["share"] >= PLACE_SHARE].sort_values(["GEOID", "share"], ascending=[True, False])
    return ov.groupby("GEOID")["NAME"].apply(lambda s: ", ".join(dict.fromkeys(s))).to_dict()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tracts", default=C.TRACT_ZIP)
    ap.add_argument("--places", default=C.PLACE_ZIP)
    ap.add_argument("--simplify", type=float, default=0.0004, help="Visvalingam tolerance in degrees (0 = none)")
    ap.add_argument("--out", default=C.DATA / "tracts_topo.js")
    a = ap.parse_args()
    C.WORK.mkdir(parents=True, exist_ok=True)

    tr = read(a.tracts).to_crs(4326)
    tr["GEOID"] = tr["GEOID"].astype(str).str.zfill(11)
    tr = tr[tr["GEOID"].str.startswith(C.STATE_FIPS)]
    if "ALAND" in tr:
        tr = tr[tr["ALAND"].astype(float) > 0].copy()
    tr["CO"] = tr["GEOID"].str[2:5]
    print(f"{len(tr):,} land tracts")

    places = place_names(tr, read(a.places).to_crs(4326)) if a.places else {}
    geo = tr[["GEOID", "CO"]].copy()
    geo["tract"] = tr["NAME"].astype(str) if "NAME" in tr else tr["GEOID"].str[5:]
    geo["place"] = geo["GEOID"].map(places).fillna("")
    geo["aland_sqmi"] = (tr["ALAND"].astype(float) / SQM_PER_SQMI).round(3) if "ALAND" in tr else ""
    geo.to_csv(C.TRACT_GEO_CSV, index=False)
    print(f"  -> {C.TRACT_GEO_CSV} ({(geo.place != '').sum():,} tracts inside a named place)")

    tracts = tr[["GEOID", "CO", "geometry"]].reset_index(drop=True)
    tracts["geometry"] = tracts.geometry.make_valid()
    counties = tracts.dissolve(by="CO", as_index=False)[["CO", "geometry"]]
    topo = tp.Topology([tracts, counties], object_name=["tracts", "counties"], prequantize=1e6,
                       toposimplify=a.simplify or False, simplify_algorithm="vw", simplify_with="simplification",
                       prevent_oversimplify=True)
    tj = json.loads(topo.to_json())
    for g in tj["objects"]["tracts"]["geometries"]:
        g["id"] = g["properties"]["GEOID"]
    for g in tj["objects"]["counties"]["geometries"]:
        g["id"] = g["properties"]["CO"]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("// Generated by pipeline/build_topology.py from Census 2020 cartographic boundaries\n")
        f.write("window.HL_TOPO = " + json.dumps(tj, separators=(",", ":")) + ";\n")
    print(f"  -> {a.out} ({len(tracts):,} tracts, {len(counties)} counties)")


if __name__ == "__main__":
    main()
